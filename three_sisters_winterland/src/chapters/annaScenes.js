const buildSettlementHubOptions = (flags) => {
  const options = [];

  if (!flags?.p2_ostmark_done) {
    options.push({ id: "hub_to_ostmark", label: "Пройти в Остмарк", next: "P2_START" });
  }
  if (!flags?.p2_windholm_done) {
    options.push({ id: "hub_to_windholm", label: "Пройти дальше в Виндхольм", next: "P2_WINDHOLM_ROAD" });
  }
  if (!flags?.p2_garrison_done) {
    options.push({ id: "hub_to_garrison", label: "Обойти густой лес", next: "D2_GARRISON_VIEW" });
  }
  if (!flags?.p2_fox_done) {
    options.push({ id: "hub_to_fox", label: "Пройти через поселения слева", next: "D9_FOX" });
  }

  if (flags?.p2_ostmark_done && flags?.p2_windholm_done && flags?.p2_garrison_done && flags?.p2_fox_done) {
    options.push({ id: "hub_to_horizon", label: "Покинуть поселения", next: "P2_HORIZON" });
  }

  return options;
};

